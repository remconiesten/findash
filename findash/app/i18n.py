class Translator:
    def __init__(self, locale: str, ui: dict[str, str], terms: dict[tuple[str, str], str]):
        self.locale = locale if locale in LOCALES else "nl"
        self._ui = ui
        self._terms = terms

    def ui(self, key: str) -> str:
        hit = self._ui.get(f"{self.locale}:{key}")
        if hit:
            return hit
        extras = {"en": EN_UI, "ru": RU_UI, "nl": NL_UI}
        pack = extras.get(self.locale) or {}
        if key in pack:
            return pack[key]
        return NL_UI.get(key, key)

    def term(self, namespace: str, source_nl: str | None) -> str:
        if not source_nl:
            return ""
        if self.locale == "nl":
            return source_nl
        hit = self._terms.get((namespace, source_nl))
        if hit:
            return hit
        packs = {
            "hoofd": (HOOFD_EN, HOOFD_RU),
            "sub": (SUB_EN, SUB_RU),
            "rekening": (REKENING_EN, REKENING_RU),
            "cc_type": (CC_TYPE_EN, CC_TYPE_RU),
        }
        pair = packs.get(namespace)
        if pair:
            table = pair[0] if self.locale == "en" else pair[1] if self.locale == "ru" else {}
            return table.get(source_nl, source_nl)
        if namespace == "af_bij":
            if self.locale == "en":
                return {"Af": "Out", "Bij": "In"}.get(source_nl, source_nl)
            if self.locale == "ru":
                return {"Af": "Расход", "Bij": "Приход"}.get(source_nl, source_nl)
        return source_nl

    def month(self, number: int, short: bool = False) -> str:
        if number < 1 or number > 12:
            return str(number)
        table = MONTHS_SHORT if short else MONTHS
        names = table.get(self.locale) or table["nl"]
        return names[number - 1]

    def ym(self, year: int, month: int, short: bool = True) -> str:
        return f"{self.month(month, short=short)} {year}"


